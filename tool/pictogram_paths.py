"""Writes lib/features/common/pictogram_paths.dart: the outlines of the
Material icons that lib/features/common/pictograms.dart uses for warning
signs and leftovers, as SVG path data in a 24x24 box, so PDFs (the paper
sheet) draw the same pictograms the worker sees on screen. The pdf package
can't read Flutter's icon font itself (CFF outlines).

Run it again whenever pictograms.dart changes icons:

    python3 -m venv <dir> && <dir>/bin/pip install fonttools
    <dir>/bin/python -I tool/pictogram_paths.py

It needs `flutter` on the PATH, to find the Flutter SDK's icon font and
icons.dart.
"""

import os
import re
import shutil
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PICTOGRAMS = os.path.join(REPO, 'lib/features/common/pictograms.dart')
OUT = os.path.join(REPO, 'lib/features/common/pictogram_paths.dart')


def flutter_root():
    flutter = shutil.which('flutter')
    if flutter is None:
        sys.exit('flutter is not on the PATH')
    return os.path.dirname(os.path.dirname(os.path.realpath(flutter)))


def icon_names(enum):
    """(value, icon name) pairs of `enum.value => Icons.name` in pictograms.dart."""
    text = open(PICTOGRAMS, encoding='utf-8').read()
    pairs = re.findall(enum + r'\.(\w+) => Icons\.(\w+)', text)
    if not pairs:
        sys.exit(f'no {enum} icons found in {PICTOGRAMS}')
    return pairs


def codepoints(root):
    icons = os.path.join(root, 'packages/flutter/lib/src/material/icons.dart')
    text = open(icons, encoding='utf-8').read()
    return {
        name: int(cp, 16)
        for name, cp in re.findall(
            r'static const IconData (\w+) = IconData\((0x[0-9a-fA-F]+)', text
        )
    }


def svg_path(font, codepoint):
    glyph_name = font.getBestCmap().get(codepoint)
    if glyph_name is None:
        return None
    glyphs = font.getGlyphSet()
    upm = font['head'].unitsPerEm
    ascent = font['hhea'].ascent
    scale = 24 / upm
    pen = SVGPathPen(glyphs, ntos=lambda v: f'{round(v, 2):g}')
    # Font units are y up from the baseline; SVG is y down from the top.
    glyphs[glyph_name].draw(
        TransformPen(pen, (scale, 0, 0, -scale, 0, ascent * scale))
    )
    return pen.getCommands()


def main():
    root = flutter_root()
    font = TTFont(
        os.path.join(root, 'bin/cache/artifacts/material_fonts/MaterialIcons-Regular.otf')
    )
    cps = codepoints(root)
    sections = []
    for enum, fn in (('WarningSign', 'warningSignPath'), ('Leftover', 'leftoverPath')):
        cases = []
        for value, icon in icon_names(enum):
            if icon not in cps:
                sys.exit(f'Icons.{icon} not found in icons.dart')
            path = svg_path(font, cps[icon])
            if not path:
                sys.exit(f'Icons.{icon} has no glyph in the font')
            cases.append(f"  {enum}.{value} => // Icons.{icon}\n    '{path}',")
        doc = 'warning sign' if enum == 'WarningSign' else 'leftover'
        sections.append(
            f'/// The {doc} pictogram as SVG path data in a 24×24 box.\n'
            f'String {fn}({enum} v) => switch (v) {{\n' + '\n'.join(cases) + '\n};\n'
        )
    out = (
        '// GENERATED by tool/pictogram_paths.py from Flutter\'s\n'
        '// MaterialIcons-Regular.otf (Material Icons, Apache License 2.0).\n'
        '// Do not edit by hand: change pictograms.dart and run the tool.\n\n'
        "import '../../domain/types.dart';\n\n"
        + '\n'.join(sections)
        + '\n/// [path] as a black (or [fill]) 24×24 SVG image.\n'
        "String pictogramSvg(String path, {String fill = '#000000'}) =>\n"
        "    '<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 24 24\">'\n"
        "    '<path d=\"$path\" fill=\"$fill\"/></svg>';\n"
    )
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(out)
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
